def search_food(query: str) -> list[tuple[str, tuple[float, float, float, float]]]:
    """
    Поиск блюда по частичному совпадению.
    Возвращает список (название, (ккал, белки, жиры, углеводы)).
    Максимум 5 результатов.
    """
    query = query.lower().strip()
    results = []

    # Сначала точное совпадение
    if query in FOODS:
        return [(query, FOODS[query])]

    # Затем частичное
    for name, values in FOODS.items():
        if query in name:
            results.append((name, values))
        if len(results) >= 5:
            break

    return results


def get_food(name: str) -> tuple[float, float, float, float] | None:
    """Возвращает нутриенты по точному названию."""
    return FOODS.get(name.lower().strip())
