def search_food(query: str) -> list[tuple[str, tuple]]:
    """Поиск по частичному совпадению. Максимум 5 результатов."""
    q = query.lower().strip()
    if q in FOODS:
        return [(q, FOODS[q])]
    results = []
    for name, vals in FOODS.items():
        if q in name:
            results.append((name, vals))
        if len(results) >= 5:
            break
    return results


def get_food(name: str) -> tuple | None:
    return FOODS.get(name.lower().strip())


